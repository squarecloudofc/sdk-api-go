package rest

import (
	"net/http"

	"github.com/squarecloudofc/sdk-api-go/v2/squarecloud"
)

var _ Workspaces = (*workspacesImpl)(nil)

func NewWorkspaces(client Client) Workspaces {
	return &workspacesImpl{client: client}
}

type Workspaces interface {
	GetWorkspaces(options ...RequestOpt) ([]squarecloud.Workspace, error)
	CreateWorkspace(name string, options ...RequestOpt) (squarecloud.WorkspaceCreated, error)
	GetWorkspace(workspaceID string, options ...RequestOpt) (squarecloud.Workspace, error)
	DeleteWorkspace(workspaceID string, options ...RequestOpt) error
	LeaveWorkspace(workspaceID string, options ...RequestOpt) error

	AddWorkspaceApplication(workspaceID, appID string, options ...RequestOpt) error
	RemoveWorkspaceApplication(workspaceID, appID string, options ...RequestOpt) error

	// AddWorkspaceMember adds a member by invite code (see
	// GetWorkspaceInviteCode — the code is generated by the joining user).
	AddWorkspaceMember(workspaceID, code string, group squarecloud.WorkspaceMemberGroup, options ...RequestOpt) error
	UpdateWorkspaceMember(workspaceID, memberID string, group squarecloud.WorkspaceMemberGroup, options ...RequestOpt) error
	RemoveWorkspaceMember(workspaceID, memberID string, options ...RequestOpt) error
	// GetWorkspaceInviteCode generates the caller's single-use invite code,
	// valid for 5 minutes.
	GetWorkspaceInviteCode(options ...RequestOpt) (squarecloud.WorkspaceInviteCode, error)
}

type workspacesImpl struct {
	client Client
}

func (s *workspacesImpl) jsonRequest(method, endpoint string, payload any, opts []RequestOpt) error {
	body, err := jsonBody(payload)
	if err != nil {
		return err
	}

	opts = append(opts, WithHeader("Content-Type", "application/json"))

	var r squarecloud.APIResponse[any]
	return s.client.Request(method, endpoint, body, &r, opts...)
}

func (s *workspacesImpl) GetWorkspaces(opts ...RequestOpt) ([]squarecloud.Workspace, error) {
	var r squarecloud.APIResponse[[]squarecloud.Workspace]
	err := s.client.Request(http.MethodGet, EndpointWorkspaces(), nil, &r, opts...)

	return r.Response, err
}

func (s *workspacesImpl) CreateWorkspace(name string, opts ...RequestOpt) (squarecloud.WorkspaceCreated, error) {
	body, err := jsonBody(map[string]string{"name": name})
	if err != nil {
		return squarecloud.WorkspaceCreated{}, err
	}

	opts = append(opts, WithHeader("Content-Type", "application/json"))

	var r squarecloud.APIResponse[squarecloud.WorkspaceCreated]
	err = s.client.Request(http.MethodPost, EndpointWorkspaces(), body, &r, opts...)

	return r.Response, err
}

func (s *workspacesImpl) GetWorkspace(workspaceID string, opts ...RequestOpt) (squarecloud.Workspace, error) {
	var r squarecloud.APIResponse[squarecloud.Workspace]
	err := s.client.Request(http.MethodGet, EndpointWorkspaceInformation(workspaceID), nil, &r, opts...)

	return r.Response, err
}

func (s *workspacesImpl) DeleteWorkspace(workspaceID string, opts ...RequestOpt) error {
	return s.jsonRequest(http.MethodDelete, EndpointWorkspaces(), map[string]string{"workspaceId": workspaceID}, opts)
}

func (s *workspacesImpl) LeaveWorkspace(workspaceID string, opts ...RequestOpt) error {
	return s.jsonRequest(http.MethodDelete, EndpointWorkspaceLeave(), map[string]string{"workspaceId": workspaceID}, opts)
}

func (s *workspacesImpl) AddWorkspaceApplication(workspaceID, appID string, opts ...RequestOpt) error {
	return s.jsonRequest(http.MethodPost, EndpointWorkspaceApplications(), map[string]string{"workspaceId": workspaceID, "appId": appID}, opts)
}

func (s *workspacesImpl) RemoveWorkspaceApplication(workspaceID, appID string, opts ...RequestOpt) error {
	return s.jsonRequest(http.MethodDelete, EndpointWorkspaceApplications(), map[string]string{"workspaceId": workspaceID, "appId": appID}, opts)
}

func (s *workspacesImpl) AddWorkspaceMember(workspaceID, code string, group squarecloud.WorkspaceMemberGroup, opts ...RequestOpt) error {
	return s.jsonRequest(http.MethodPost, EndpointWorkspaceMembers(), map[string]any{
		"workspaceId": workspaceID,
		"code":        code,
		"group":       group,
	}, opts)
}

func (s *workspacesImpl) UpdateWorkspaceMember(workspaceID, memberID string, group squarecloud.WorkspaceMemberGroup, opts ...RequestOpt) error {
	return s.jsonRequest(http.MethodPatch, EndpointWorkspaceMembers(), map[string]any{
		"workspaceId": workspaceID,
		"memberId":    memberID,
		"group":       group,
	}, opts)
}

func (s *workspacesImpl) RemoveWorkspaceMember(workspaceID, memberID string, opts ...RequestOpt) error {
	return s.jsonRequest(http.MethodDelete, EndpointWorkspaceMembers(), map[string]string{"workspaceId": workspaceID, "memberId": memberID}, opts)
}

func (s *workspacesImpl) GetWorkspaceInviteCode(opts ...RequestOpt) (squarecloud.WorkspaceInviteCode, error) {
	var r squarecloud.APIResponse[squarecloud.WorkspaceInviteCode]
	err := s.client.Request(http.MethodGet, EndpointWorkspaceInviteCode(), nil, &r, opts...)

	return r.Response, err
}
